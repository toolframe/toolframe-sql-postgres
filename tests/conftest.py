class PrivateDatabase(dict):
    def __repr__(self):
        return "<isolated PostgreSQL test database; credentials redacted>"


@contextmanager
def caller(
    owner="alpha",
    generation="generation-1",
    root="root-1",
    *,
    admin=False,
    deadline=None,
    application="application-1",
):
    token = call_context.set(
        {
            "application_id": application,
            "owner": owner,
            "owner_generation": generation,
            "root_id": root,
            "management": admin,
            "deadline": deadline or time.time() + 30,
        }
    )
    try:
        yield
    finally:
        call_context.reset(token)


def schema(*extra):
    migrations = (
        Migration(
            revision="v1",
            sql="CREATE TABLE entries(id INTEGER PRIMARY KEY, label TEXT NOT NULL);",
            dialects={
                "postgresql": "CREATE TABLE entries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label TEXT NOT NULL);"
            },
        ),
        *extra,
    )
    return StoreSchema(
        revision=migrations[-1].revision, migrations=migrations
    ).model_dump()


@pytest.fixture
def database(monkeypatch, request):
    admin = os.environ.get("TOOLFRAME_POSTGRES_TEST_ADMIN_DSN")
    if not admin:
        pytest.skip("Set TOOLFRAME_POSTGRES_TEST_ADMIN_DSN for real PostgreSQL tests")
    database = "tf_test_" + uuid.uuid4().hex
    env = provision(
        admin, database, "application-1", getattr(request, "param", ["alpha", "beta"])
    )
    for key, value in env.items():
        monkeypatch.setenv(key, value)
    try:
        yield PrivateDatabase(admin=admin, database=database, env=env)
    finally:
        cleanup_database(admin, database, json.loads(env["TOOLFRAME_POSTGRES_STORES"]))


def cleanup_database(admin, database, owners, application="application-1"):
    with psycopg.connect(admin, autocommit=True) as connection:
        connection.execute(
            sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(
                sql.Identifier(database)
            )
        )
        for owner in owners:
            values = names(application, owner, database=database)
            for key in ("controller", "runtime"):
                connection.execute(
                    sql.SQL("DROP ROLE IF EXISTS {}").format(
                        sql.Identifier(values[key])
                    )
                )
        connection.execute(
            sql.SQL("DROP ROLE IF EXISTS {}").format(
                sql.Identifier(names(application, database=database)["manager"])
            )
        )


